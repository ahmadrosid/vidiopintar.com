import { describe, expect, test } from "bun:test";
import type { CaptionTrackInfo } from "youtube-transcript-plus";
import {
  mapTranscriptSegments,
  mapVideoDetails,
  pickCaptionTrack,
} from "./transcript-api";

function track(
  languageCode: string,
  isAutoGenerated: boolean,
): CaptionTrackInfo {
  return { languageCode, languageName: languageCode, isAutoGenerated };
}

describe("pickCaptionTrack", () => {
  test("returns null when there are no tracks", () => {
    expect(pickCaptionTrack([])).toBeNull();
  });

  test("prefers human id over ASR en", () => {
    const picked = pickCaptionTrack(
      [track("en", true), track("id", false)],
      "id",
    );

    expect(picked?.languageCode).toBe("id");
  });

  test("matches language prefix", () => {
    const picked = pickCaptionTrack([track("id-ID", false)], "id");

    expect(picked?.languageCode).toBe("id-ID");
  });

  test("falls back to en before id when no preference matches", () => {
    const picked = pickCaptionTrack(
      [track("id", false), track("en", false)],
      "fr",
    );

    expect(picked?.languageCode).toBe("en");
  });

  test("falls back to any ASR track", () => {
    const picked = pickCaptionTrack([track("de", true)]);

    expect(picked?.languageCode).toBe("de");
  });
});

describe("mapTranscriptSegments", () => {
  test("maps offset to start", () => {
    expect(
      mapTranscriptSegments([
        { text: "Hello", offset: 1.5, duration: 2, lang: "en" },
      ]),
    ).toEqual([{ text: "Hello", start: 1.5, duration: 2 }]);
  });

  test("decodes numeric and nested HTML entities", () => {
    const [segment] = mapTranscriptSegments([
      { text: "It&#39;s &amp;amp; good", offset: 0, duration: 1, lang: "en" },
    ]);

    expect(segment.text).toBe("It's & good");
  });
});

describe("mapVideoDetails", () => {
  test("returns undefined without details", () => {
    expect(mapVideoDetails()).toBeUndefined();
  });
});
