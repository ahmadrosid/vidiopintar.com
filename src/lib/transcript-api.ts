import type {
  CaptionTrackInfo,
  TranscriptSegment,
  VideoDetails,
} from "youtube-transcript-plus";

export interface TranscriptApiSegment {
  text: string;
  start: number;
  duration: number;
}

export interface TranscriptApiMetadata {
  title?: string;
  author_name?: string;
  author_url?: string;
  thumbnail_url?: string;
}

export interface TranscriptApiResponse {
  video_id: string;
  language: string;
  transcript: TranscriptApiSegment[];
  metadata?: TranscriptApiMetadata;
}

function decodeHtmlEntities(text: string): string {
  const named = new Map<string, string>([
    ["&amp;", "&"],
    ["&lt;", "<"],
    ["&gt;", ">"],
    ["&quot;", '"'],
    ["&apos;", "'"],
    ["&#39;", "'"],
    ["&nbsp;", " "],
  ]);

  const once = (value: string) =>
    value
      .replace(
        /&(?:amp|lt|gt|quot|apos|nbsp|#39);/g,
        (match) => named.get(match) ?? match,
      )
      .replace(/&#(\d+);/g, (_, code) =>
        String.fromCharCode(parseInt(code, 10)),
      )
      .replace(/&#x([0-9a-fA-F]+);/g, (_, code) =>
        String.fromCharCode(parseInt(code, 16)),
      );

  let decoded = text;
  let prev = "";

  while (prev !== decoded) {
    prev = decoded;
    decoded = once(decoded);
  }

  return decoded;
}

function matchesLanguagePrefix(languageCode: string, prefix: string): boolean {
  const code = languageCode.toLowerCase();
  const needle = prefix.toLowerCase();

  return code === needle || code.startsWith(`${needle}-`);
}

export function pickCaptionTrack(
  tracks: CaptionTrackInfo[],
  preferred?: string,
): CaptionTrackInfo | null {
  if (tracks.length === 0) {
    return null;
  }

  const preferredCode = preferred?.trim().toLowerCase();
  const fallbacks = ["en", "id"].filter((code) => code !== preferredCode);

  if (preferredCode) {
    const humanPreferred = tracks.find(
      (track) =>
        !track.isAutoGenerated &&
        matchesLanguagePrefix(track.languageCode, preferredCode),
    );

    if (humanPreferred) {
      return humanPreferred;
    }

    const asrPreferred = tracks.find(
      (track) =>
        track.isAutoGenerated &&
        matchesLanguagePrefix(track.languageCode, preferredCode),
    );

    if (asrPreferred) {
      return asrPreferred;
    }
  }

  for (const code of fallbacks) {
    const human = tracks.find(
      (track) =>
        !track.isAutoGenerated &&
        matchesLanguagePrefix(track.languageCode, code),
    );

    if (human) {
      return human;
    }
  }

  for (const code of fallbacks) {
    const asr = tracks.find(
      (track) =>
        track.isAutoGenerated &&
        matchesLanguagePrefix(track.languageCode, code),
    );

    if (asr) {
      return asr;
    }
  }

  return tracks.find((track) => track.isAutoGenerated) ?? null;
}

export function mapTranscriptSegments(
  segments: TranscriptSegment[],
): TranscriptApiSegment[] {
  return segments.map((segment) => ({
    text: decodeHtmlEntities(segment.text),
    start: segment.offset,
    duration: segment.duration,
  }));
}

export function mapVideoDetails(
  details?: VideoDetails,
): TranscriptApiMetadata | undefined {
  if (!details) {
    return undefined;
  }

  const thumbnail =
    details.thumbnails?.at(-1)?.url ?? details.thumbnails?.[0]?.url;

  return {
    title: details.title,
    author_name: details.author,
    thumbnail_url: thumbnail,
  };
}
